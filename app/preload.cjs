const { contextBridge, ipcRenderer } = require("electron");

const call = (channel, ...args) => ipcRenderer.invoke(channel, ...args);

contextBridge.exposeInMainWorld("api", {
  language: ipcRenderer.sendSync("get-language"),
  setLanguage: (language) => call("set-language", language),
  state: () => call("state"),
  openTerminal: (name) => call("open-terminal", name),
  wake: (name) => call("wake", name),
  updateMachine: (name) => call("update-machine", name),
  setClient: (client, enabled) => call("set-client", client, enabled),
  saveMachine: (name, values) => call("save-machine", name, values),
  whatsappSync: () => call("whatsapp-sync"),
  whatsappLogin: () => call("whatsapp-login"),
  whatsappLoginCancel: () => call("whatsapp-login-cancel"),
  whatsappDisconnect: () => call("whatsapp-disconnect"),
  whatsappAudio: (enabled) => call("whatsapp-audio", enabled),
  onAudioProgress: (listener) => ipcRenderer.on("whatsapp-audio", (_event, payload) => listener(payload)),
  remoteSet: (enabled) => call("remote-set", enabled),
  remoteCode: () => call("remote-code"),
  remoteCopy: () => call("remote-copy"),
  remoteRevoke: (id) => call("remote-revoke", id),
  panelResize: (height) => call("panel-resize", height),
  openMain: (tab) => call("open-main", tab),
  onSelectTab: (listener) => ipcRenderer.on("select-tab", (_event, tab) => listener(tab)),
  onPanelShown: (listener) => ipcRenderer.on("panel-shown", () => listener()),
  onStateChanged: (listener) => ipcRenderer.on("state-changed", () => listener()),
  tasks: (op, args) => call("tasks", op, args),
  openTasks: (id) => call("open-tasks", id),
  onFocusTask: (listener) => ipcRenderer.on("focus-task", (_event, id) => listener(id)),
  calendarStatus: () => call("calendar-status"),
  calendarRequest: () => call("calendar-request"),
  calendarEvents: (from, to) => call("calendar-events", from, to),
  auditList: () => call("audit-list"),
  auditClear: () => call("audit-clear"),
  tasksSetHub: (enabled) => call("tasks-set-hub", enabled),
  tasksSetHost: (host) => call("tasks-set-host", host),
  vaultAdd: () => call("vault-add"),
  vaultSet: (path, enabled) => call("vault-set", path, enabled),
  gmailAdd: (values) => call("gmail-add", values),
  gmailRemove: (email) => call("gmail-remove", email),
  setPolicy: (patch) => call("set-policy", patch),
  nightlight: (op, args) => call("nightlight", op, args),
  vpn: (op, args) => call("vpn", op, args),
  awake: (op, args) => call("awake", op, args),
  onAwakeChanged: (listener) => ipcRenderer.on("awake-changed", () => listener()),
  onNightLightChanged: (listener) => ipcRenderer.on("nightlight-changed", () => listener()),
  setOnboarded: (value) => call("set-onboarded", value),
  aboutSave: (text) => call("about-save", text),
  aboutOpen: () => call("about-open"),
  openLink: (name) => call("open-link", name),
  openTailscale: () => call("open-tailscale"),
  openPrivacy: (pane) => call("open-privacy", pane),
  copyDiagnostics: () => call("copy-diagnostics"),
  restart: () => call("restart"),
  setOpenAtLogin: (enabled) => call("set-open-at-login", enabled),
  quit: () => call("quit"),
  updatesState: () => call("updates-state"),
  updatesCheck: () => call("updates-check"),
  updatesInstall: () => call("updates-install"),
  updatesSetAuto: (enabled) => call("updates-set-auto", enabled),
  onUpdatesChanged: (listener) => ipcRenderer.on("updates-changed", () => listener()),
  onLoginEvent: (listener) => ipcRenderer.on("whatsapp-login", (_event, payload) => listener(payload)),
});
